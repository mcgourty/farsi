// Writes js/legacy-keys.js: every v1 store key (the old cardKey) -> the new
// card id(s). It pairs the legacy app's CARDS with the new deck card by card
// and refuses to write if any card's text differs, so it can only be run
// against data that has not been edited since the split. The output is
// committed and must never be regenerated after card text changes.
'use strict';

const fs = require('fs');
const path = require('path');
const { loadOldApp, LEGACY_REF } = require('./old-app');
const { loadApp, ROOT } = require('../load');

// Breakdowns rewritten on purpose since the split (text is unchanged):
// bardāshtan is built as bar + verb instead of "irregular — memorize it".
const BREAKDOWN_FIXED = /^verb\.bardashtan\./;

function pairDecks() {
  const old = loadOldApp();
  if (!old) throw new Error('git show failed; run inside the repo');
  const oldCards = JSON.parse(old.run('JSON.stringify(CARDS.map(c => Object.assign({ key: cardKey(c) }, c)))'));
  const { F } = loadApp();
  // The legacy app had every verb form; the default deck is trimmed now.
  if (F.verbs.config) { F.verbs.config.allForms = true; F.cards.build(); }
  const cards = F.cards.all;
  if (oldCards.length !== cards.length) throw new Error(`card count differs: old ${oldCards.length}, new ${cards.length}`);
  const FIELDS = ['session', 'type', 'direction', 'farsi', 'pinglish', 'english', 'breakdown',
    'name', 'sound', 'isolated', 'initial', 'medial', 'final', 'notes'];
  oldCards.forEach((o, i) => {
    const n = cards[i];
    for (const f of FIELDS) {
      if (f === 'breakdown' && BREAKDOWN_FIXED.test(n.id)) continue;
      if ((o[f] ?? null) !== (n[f] ?? null)) {
        throw new Error(`card ${i} (${n.id}) field ${f} differs: ${JSON.stringify(o[f])} vs ${JSON.stringify(n[f])}`);
      }
    }
  });
  return { oldCards, cards };
}

function buildMap() {
  const { oldCards, cards } = pairDecks();
  const map = {};
  oldCards.forEach((o, i) => { (map[o.key] = map[o.key] || []).push(cards[i].id); });
  return map;
}

if (require.main === module) {
  const map = buildMap();
  const keys = Object.keys(map);
  const shared = keys.filter(k => map[k].length > 1).length;
  let out = `// GENERATED by tools/legacy/build-legacy-keys.js from flashcards.html @ ${LEGACY_REF}.\n`;
  out += '// Maps every key of the v1 store (farsi-flashcards-v1) to the card id(s)\n';
  out += '// that replaced it. Only loaded when a v1 store needs migrating.\n';
  out += `// ${keys.length} old keys, ${shared} of them shared by more than one card.\n`;
  out += '// Frozen: do not regenerate after card text has changed.\n';
  out += '(function (root) {\n  (root.F = root.F || {}).LEGACY_KEYS = {\n';
  for (const k of keys) out += `    ${JSON.stringify(k)}: ${JSON.stringify(map[k])},\n`;
  out += '  };\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
  fs.writeFileSync(path.join(ROOT, 'js', 'legacy-keys.js'), out);
  console.log(`wrote js/legacy-keys.js: ${keys.length} keys, ${shared} shared`);
}

module.exports = { pairDecks, buildMap };
